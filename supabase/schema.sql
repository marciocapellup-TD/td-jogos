create table if not exists groups (
  id smallint primary key,
  nome text not null,
  cor text not null
);

create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome_exibicao text not null,
  email text unique,
  group_id smallint references groups(id),
  role text not null default 'user' check (role in ('user','admin','superadmin')),
  ativo boolean not null default true,
  created_at timestamptz default now()
);

create table if not exists pending_claims (
  -- profiles "de espera" seedados antes do usuário logar pela primeira vez
  id smallint generated by default as identity primary key,
  nome_exibicao text not null,
  email text,
  group_id smallint references groups(id),
  role text not null default 'user',
  claimed_by uuid references auth.users(id),
  claimed_at timestamptz
);

create table if not exists posts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references profiles(id) on delete cascade,
  categoria text not null check (categoria in ('energia','movimento','mental')),
  data_registro date not null default current_date,
  quantidade_frutas smallint check (quantidade_frutas between 1 and 2),
  minutos smallint check (minutos > 0),
  foto_url text not null,
  pontos smallint not null default 0,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid references profiles(id),
  reviewed_at timestamptz,
  motivo_reprovacao text,
  created_at timestamptz default now(),
  constraint chk_energia check (
    categoria != 'energia' or (quantidade_frutas is not null and minutos is null)
  ),
  constraint chk_mov_mental check (
    categoria = 'energia' or (minutos is not null and quantidade_frutas is null)
  )
);

create index if not exists idx_posts_user_data on posts (user_id, data_registro);
create index if not exists idx_posts_status on posts (status);

create table if not exists challenge_config (
  id smallint primary key default 1 check (id = 1),
  data_inicio date not null,
  data_fim date not null
);

